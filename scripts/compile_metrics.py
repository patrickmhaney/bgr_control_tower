def target_docs(dimensions, models, metrics):
    import csv
    map_path = os.path.join(ROOT, "seeds", "process_metric_map.csv")
    process_map = {}
    if os.path.exists(map_path):
        with open(map_path) as fh:
            for row in csv.DictReader(fh):
                process_map.setdefault(row["metric_name"], []).append(
                    f"{row['process_code']} {row['slot']}")

    lines = [
        "# Metric catalogue",
        "",
        f"<!-- {GENERATED_BANNER} -->",
        "",
        "One row per metric definition. A metric appears once here however many",
        "dashboards it lands on - the process column is read from",
        "`seeds/process_metric_map.csv`, not from the definition.",
        "",
        "| Metric | Label | Status | Processes | Owner | Base model | Grain |",
        "|---|---|---|---|---|---|---|",
    ]
    for metric in metrics:
        procs = ", ".join(process_map.get(metric["name"], [])) or "_none_"
        lines.append(
            f"| `{metric['name']}` | {metric['label']} | {metric['status']} | {procs} "
            f"| {metric.get('owner')} | `{metric.get('base_model') or '-'}` "
            f"| {' '.join(metric['grain'].split())} |"
        )

    lines += ["", "---", ""]
    for metric in metrics:
        lines += [
            f"## {metric['label']} (`{metric['name']}`)",
            "",
            f"**Status** {metric['status']}"
            + (f" · **Data quality metric**" if metric.get("is_data_quality") else "")
            + f" · **Owner** {metric.get('owner')}"
            + (f" (proposed: {metric['owner_proposed']})" if metric.get("owner_proposed") else ""),
            "",
            " ".join(metric["description"].split()),
            "",
            f"**Grain** {' '.join(metric['grain'].split())}",
            "",
        ]
        procs = process_map.get(metric["name"], [])
        lines += [
            "**Appears on** " + (", ".join(procs) if procs else
                                 "_no dashboard - registered but unmapped_"),
            "",
        ]
        if metric["status"] == "blocked":
            lines += ["**Blocked** " + " ".join(metric["blocked_reason"].split()), ""]
            if metric.get("unblock_requires"):
                lines += ["**To unblock**", ""]
                lines += [f"- {' '.join(r.split())}" for r in metric["unblock_requires"]]
                lines += [""]
        else:
            lines += [
                f"**Numerator** `{agg_sql(metric['numerator'])}`  ",
                f"**Denominator** `{agg_sql(metric['denominator'])}`  ",
                (f"**Metric filters** "
                 + ", ".join(f"`{describe_filter(f)}`" for f in metric["filters"])
                 + "  ") if metric.get("filters") else "",
                f"**Base model** `{metric['base_model']}`  ",
                f"**Dimensions** {', '.join(metric.get('dimensions') or []) or '_none_'}  ",
                f"**Generated SQL model** `mtr_{metric['name']}`  ",
                f"**Re-aggregatable** {'yes' if is_reaggregatable(metric) else 'no'}",
                "",
            ]
            if metric.get("provisional_reason"):
                lines += ["**Provisional because** "
                          + " ".join(metric["provisional_reason"].split()), ""]
            if metric.get("companion_metric"):
                lines += [f"**Must be published with** `{metric['companion_metric']}`", ""]
        if metric.get("caveats"):
            lines += ["**Caveats**", ""]
            lines += [f"- {' '.join(c.split())}" for c in metric["caveats"]]
            lines += [""]
        if metric.get("lineage_notes"):
            lines += ["**Lineage**", "",
                      " ".join(metric["lineage_notes"].split()), ""]
        lines += [f"_Defined in `{metric['_file']}`._", "", "---", ""]

    return [write("docs/metric_catalog.md", "\n".join(lines))]


def target_seed(dimensions, models, metrics):
    """The registry as a dbt seed.

    Loading it into the warehouse lets dbt enforce referential integrity
    between seeds/process_metric_map.csv and the registry with an ordinary
    relationships test, instead of that check living only in this script. It
    also means Power BI can bind metric metadata - status, owner, caveats -
    without a second source.
    """
    import csv as _csv
    import io

    buf = io.StringIO()
    writer = _csv.writer(buf, lineterminator="\n")
    writer.writerow([
        "metric_name", "metric_label", "status", "is_data_quality", "base_model",
        "grain", "owner", "owner_proposed", "format", "direction",
        "is_reaggregatable", "sql_model", "definition_file", "description",
        "blocked_reason",
    ])
    for metric in metrics:
        blocked = metric["status"] == "blocked"
        writer.writerow([
            metric["name"],
            metric["label"],
            metric["status"],
            str(bool(metric.get("is_data_quality"))).lower(),
            metric.get("base_model") or "",
            " ".join(metric["grain"].split()),
            metric.get("owner") or "",
            metric.get("owner_proposed") or "",
            metric.get("format") or "",
            metric.get("direction") or "",
            "" if blocked else str(bool(is_reaggregatable(metric))).lower(),
            "" if blocked else f"mtr_{metric['name']}",
            metric["_file"],
            " ".join(metric["description"].split()),
            " ".join((metric.get("blocked_reason") or "").split()),
        ])
    return [write("seeds/metric_registry.csv", buf.getvalue())]


TARGETS = {
    "sql": target_sql,
    "seed": target_seed,
    "json": target_json,
    "docs": target_docs,
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("targets", nargs="*", default=None,
                        help=f"targets to compile; default all of {sorted(TARGETS)}")
    parser.add_argument("--check", action="store_true",
                        help="validate the registry and exit without writing")
    args = parser.parse_args()

    dimensions, models, metrics = load_registry()
    try:
        validate(dimensions, models, metrics)
    except RegistryError as exc:
        print("Registry validation failed:\n" + str(exc), file=sys.stderr)
        return 1

    counts = {}
    for metric in metrics:
        counts[metric["status"]] = counts.get(metric["status"], 0) + 1
    print(f"Registry OK: {len(metrics)} metrics "
          + ", ".join(f"{n} {s}" for s, n in sorted(counts.items())))

    if args.check:
        return 0

    chosen = args.targets or sorted(TARGETS)
    unknown = [t for t in chosen if t not in TARGETS]
    if unknown:
        print(f"Unknown target(s) {unknown}; available: {sorted(TARGETS)}", file=sys.stderr)
        return 1

    for name in chosen:
        written = TARGETS[name](dimensions, models, metrics)
        print(f"  {name:14} -> {len(written)} file(s)")
        for path in written:
            print(f"                   {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
