"""Compile the tool-neutral metric registry into every artefact that needs it.

    python scripts/compile_metrics.py            # all targets
    python scripts/compile_metrics.py --check     # validate only
    python scripts/compile_metrics.py sql json    # named targets

Why this exists
---------------
The high-risk idea in the design is generating both the warehouse SQL and the
Power BI measures from one metric definition. If a metric is defined twice -
once in SQL and once in DAX - the two will disagree, and the disagreement will
surface in a meeting rather than in a test. This script is the proof that they
need only be defined once.

Targets
-------
sql    models/marts/metrics/mtr_<name>.sql     dbt models, one per active metric
seed   seeds/metric_registry.csv               the registry as a dbt seed
json   exports/semantic/metric_registry.json   machine-readable contract for agents
docs   docs/metric_catalog.md                  the human-readable catalogue

The DAX measures are not a target here: scripts/export_powerbi.py imports
dax_measure() and writes them straight into the Power BI model it generates.

Every target reads the same registry. Adding a target does not touch a metric
definition, and changing a metric definition does not touch a target.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import date

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEMANTIC = os.path.join(ROOT, "semantic")

GENERATED_BANNER = (
    "Generated by scripts/compile_metrics.py from semantic/metrics/. "
    "Do not edit by hand - edit the metric definition and recompile."
)

AGGS = {
    "sum": "sum({expr})",
    "count": "count({expr})",
    "count_distinct": "count(distinct {expr})",
    "avg": "avg({expr})",
    "min": "min({expr})",
    "max": "max({expr})",
}

# Aggregations whose pre-aggregated result can be summed back up to a coarser
# grain. count_distinct cannot: summing distinct counts double-counts anything
# that spans two dimension values.
REAGGREGATABLE = {"sum", "count"}

DAX_AGG = {
    "sum": "SUM({table}[{col}])",
    "count": "COUNTA({table}[{col}])",
    "count_distinct": "DISTINCTCOUNT({table}[{col}])",
    "avg": "AVERAGE({table}[{col}])",
    "min": "MIN({table}[{col}])",
    "max": "MAX({table}[{col}])",
}

DAX_FORMAT = {
    "percent": '"0.0%"',
    "currency_usd": '"\\$#,0.00"',
    "days": '"#,0.0"',
    "count": '"#,0"',
}

# --------------------------------------------------------------------------
# Filters
#
# A filter is a structured triple - column, op, and a value for the comparison
# ops - never a SQL string. Both renderers (SQL and DAX) map the op to their
# own dialect from the table below, so there is no parsing anywhere and a
# translation bug is unrepresentable rather than merely guarded against.
#
# This replaced a `str.split`-based SQL translator that silently mangled `>=`
# into a column named `days_late >` - the exact class of bug this shape makes
# impossible. It also means the supported grammar is declared and finite
# instead of "whatever the parser happens to cope with".
#
# `column` is strictly a column on the base model. A metric needing a
# derivation puts it on the fact, which is already this project's rule.
# --------------------------------------------------------------------------

#: op -> (needs a value, SQL template, DAX template, arity note)
OPS = {
    "is_true":     (False, "{c}",                 "{t}[{c}] = TRUE()"),
    "is_false":    (False, "not {c}",             "{t}[{c}] = FALSE()"),
    "is_null":     (False, "{c} is null",         "ISBLANK({t}[{c}])"),
    "is_not_null": (False, "{c} is not null",     "NOT ISBLANK({t}[{c}])"),
    "eq":          (True,  "{c} = {v}",           "{t}[{c}] = {v}"),
    "ne":          (True,  "{c} <> {v}",          "{t}[{c}] <> {v}"),
    "gt":          (True,  "{c} > {v}",           "{t}[{c}] > {v}"),
    "gte":         (True,  "{c} >= {v}",          "{t}[{c}] >= {v}"),
    "lt":          (True,  "{c} < {v}",           "{t}[{c}] < {v}"),
    "lte":         (True,  "{c} <= {v}",          "{t}[{c}] <= {v}"),
    "in":          (True,  None,                  None),   # rendered specially
}


def sql_literal(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def dax_literal(value):
    if isinstance(value, bool):
        return "TRUE()" if value else "FALSE()"
    if isinstance(value, (int, float)):
        return str(value)
    return '"' + str(value).replace('"', '""') + '"'


def filter_sql(spec):
    column, op = spec["column"], spec["op"]
    if op == "in":
        values = ", ".join(sql_literal(v) for v in spec["value"])
        return f"{column} in ({values})"
    return OPS[op][1].format(c=column, v=sql_literal(spec.get("value")))


def filter_dax(table, spec):
    column, op = spec["column"], spec["op"]
    if op == "in":
        clauses = " || ".join(
            f"{table}[{column}] = {dax_literal(v)}" for v in spec["value"])
        return f"FILTER(ALL({table}[{column}]), {clauses})"
    return OPS[op][2].format(t=table, c=column, v=dax_literal(spec.get("value")))


def filters_sql(specs):
    return [filter_sql(f) for f in (specs or [])]


def describe_filter(spec):
    """Human-readable form, for docs and catalogue output."""
    if spec["op"] == "in":
        return f"{spec['column']} in ({', '.join(str(v) for v in spec['value'])})"
    if OPS[spec["op"]][0]:
        return f"{spec['column']} {spec['op']} {spec['value']}"
    return f"{spec['column']} {spec['op'].replace('_', ' ')}"


