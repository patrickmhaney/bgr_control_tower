def target_sql(dimensions, models, metrics):
    written = []
    for metric in active_metrics(metrics):
        base = metric["base_model"]
        bound = models[base].get("dimensions") or {}
        dims = metric.get("dimensions") or []

        select_lines, group_by = [], []
        for i, dim in enumerate(dims, start=1):
            key = dimensions[dim]["key"]
            column = bound[dim]
            select_lines.append(
                f"        {column}" if column == key else f"        {column} as {key}")
            group_by.append(str(i))

        num = agg_sql(metric["numerator"])
        den = agg_sql(metric["denominator"])
        filters = filters_sql(metric.get("filters"))
        where = ""
        if filters:
            where = "\n    where " + "\n      and ".join(filters)

        select_lines.append(f"        {num} as numerator")
        select_lines.append(f"        {den} as denominator")

        group_clause = f"\n    group by {', '.join(group_by)}" if group_by else ""

        header = [
            f"-- {GENERATED_BANNER}",
            f"-- Metric: {metric['name']} ({metric['label']})",
            f"-- Status: {metric['status']}",
            f"-- Grain of the denominator: {metric['grain']}",
            "--",
            f"-- Numerator:   {num}",
            f"-- Denominator: {den}",
        ]
        if not is_reaggregatable(metric):
            header += [
                "--",
                "-- NOT RE-AGGREGATABLE. The denominator is a distinct count, so",
                "-- summing this model's numerator and denominator across dimension",
                "-- values will over-count. Correct only at the grain below.",
            ]
        header += ["", ""]

        body = (
            "with base as (\n\n"
            f"    select\n" + ",\n".join(select_lines) + "\n\n"
            f"    from {{{{ ref('{base}') }}}}"
            + where
            + group_clause
            + "\n\n),\n\n"
            "final as (\n\n"
            "    select\n"
            + "".join(f"        {dimensions[d]['key']},\n" for d in dims)
            + "        numerator,\n"
            "        denominator,\n"
            # cast so this is not DuckDB-only: two BIGINT sides give integer
            # division in Postgres, SQL Server and Snowflake, where every
            # count-based ratio metric would return 0.
            "        cast(numerator as double) / nullif(denominator, 0) as metric_value,\n"
            f"        '{metric['name']}' as metric_name,\n"
            f"        '{metric['status']}' as metric_status\n\n"
            "    from base\n\n"
            ")\n\n"
            "select * from final\n"
        )
        written.append(write(f"models/marts/metrics/mtr_{metric['name']}.sql",
                             "\n".join(header) + body))

    # A schema file so the generated models are documented in dbt docs too.
    schema = {"version": 2, "models": []}
    for metric in active_metrics(metrics):
        schema["models"].append({
            "name": f"mtr_{metric['name']}",
            "description": (
                f"GENERATED. {metric['label']} ({metric['status']}). "
                f"Grain: {metric['grain']} "
                f"Definition: {metric['_file']}. "
                + ("Re-aggregatable across dimensions."
                   if is_reaggregatable(metric)
                   else "NOT re-aggregatable - the denominator is a distinct count.")
            ),
            "columns": [
                {"name": "numerator", "description": metric["numerator"].get("label", "")},
                {"name": "denominator", "description": metric["denominator"].get("label", "")},
                {"name": "metric_value", "description": "numerator / denominator"},
            ],
        })
    written.append(write("models/marts/metrics/_metrics__models.yml",
                         f"# {GENERATED_BANNER}\n"
                         + yaml.safe_dump(schema, sort_keys=False, width=100)))
    return written


