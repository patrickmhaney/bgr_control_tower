def target_seed(dimensions, models, metrics):
    """The registry as a dbt seed.

    Loading it into the warehouse lets dbt enforce referential integrity
    between seeds/process_metric_map.csv and the registry with an ordinary
    relationships test, instead of that check living only in this script. It
    also means Power BI can bind metric metadata - status, owner, caveats -
    without a second source.
    """
    import csv as _csv
    import io

    buf = io.StringIO()
    writer = _csv.writer(buf, lineterminator="\n")
    writer.writerow([
        "metric_name", "metric_label", "status", "is_data_quality", "base_model",
        "grain", "owner", "owner_proposed", "format", "direction",
        "is_reaggregatable", "sql_model", "definition_file", "description",
        "blocked_reason",
    ])
    for metric in metrics:
        blocked = metric["status"] == "blocked"
        writer.writerow([
            metric["name"],
            metric["label"],
            metric["status"],
            str(bool(metric.get("is_data_quality"))).lower(),
            metric.get("base_model") or "",
            " ".join(metric["grain"].split()),
            metric.get("owner") or "",
            metric.get("owner_proposed") or "",
            metric.get("format") or "",
            metric.get("direction") or "",
            "" if blocked else str(bool(is_reaggregatable(metric))).lower(),
            "" if blocked else f"mtr_{metric['name']}",
            metric["_file"],
            " ".join(metric["description"].split()),
            " ".join((metric.get("blocked_reason") or "").split()),
        ])
    return [write("seeds/metric_registry.csv", buf.getvalue())]


TARGETS = {
    "sql": target_sql,
    "seed": target_seed,
    "dbt_semantic": target_dbt_semantic,
    "dax": target_dax,
    "tmdl": target_tmdl,
    "cube": target_cube,
    "json": target_json,
    "docs": target_docs,
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("targets", nargs="*", default=None,
                        help=f"targets to compile; default all of {sorted(TARGETS)}")
    parser.add_argument("--check", action="store_true",
                        help="validate the registry and exit without writing")
    args = parser.parse_args()

    dimensions, models, metrics = load_registry()
    try:
        validate(dimensions, models, metrics)
    except RegistryError as exc:
        print("Registry validation failed:\n" + str(exc), file=sys.stderr)
        return 1

    counts = {}
    for metric in metrics:
        counts[metric["status"]] = counts.get(metric["status"], 0) + 1
    print(f"Registry OK: {len(metrics)} metrics "
          + ", ".join(f"{n} {s}" for s, n in sorted(counts.items())))

    if args.check:
        return 0

    chosen = args.targets or sorted(TARGETS)
    unknown = [t for t in chosen if t not in TARGETS]
    if unknown:
        print(f"Unknown target(s) {unknown}; available: {sorted(TARGETS)}", file=sys.stderr)
        return 1

    for name in chosen:
        written = TARGETS[name](dimensions, models, metrics)
        print(f"  {name:14} -> {len(written)} file(s)")
        for path in written:
            print(f"                   {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
