def target_json(dimensions, models, metrics):
    """The contract an AI agent reads.

    Deliberately includes the blocked metrics and the caveats. An agent that
    can see "Return Rate exists and is blocked because no returns object
    exists" answers the question correctly; an agent that cannot see it invents
    a number.
    """
    payload = {
        "generated_at": date.today().isoformat(),
        "generated_by": "scripts/compile_metrics.py",
        # Read from the project vars rather than hardcoded: open question 10 is
        # the one that changes this value, and this JSON is what the agent reads.
        "reporting_currency": project_var("reporting_currency", "USD"),
        "dimensions": {
            name: {
                "label": d["label"],
                "model": d["model"],
                "key": d["key"],
                "description": " ".join((d.get("description") or "").split()),
                "attributes": d.get("attributes", []),
            }
            for name, d in dimensions.items()
        },
        "models": {
            name: {
                "label": m.get("label"),
                "grain": m.get("grain"),
                "description": " ".join((m.get("description") or "").split()),
                "dimensions": list((m.get("dimensions") or {}).keys()),
                # The fact column that reaches each dimension. A consumer that
                # has to query the base model directly - which ask_metric.py
                # does for metrics the registry marks non-re-aggregatable -
                # needs the binding, not just the dimension name.
                "dimension_columns": dict(m.get("dimensions") or {}),
                "degenerate_attributes": list((m.get("degenerate") or {}).keys()),
            }
            for name, m in models.items()
        },
        "metrics": [],
    }

    for metric in metrics:
        entry = {
            "name": metric["name"],
            "label": metric["label"],
            "status": metric["status"],
            "is_data_quality": bool(metric.get("is_data_quality")),
            "description": " ".join(metric["description"].split()),
            "grain": metric["grain"],
            "base_model": metric["base_model"],
            "dimensions": metric.get("dimensions") or [],
            "format": metric.get("format"),
            "direction": metric.get("direction"),
            "owner": metric.get("owner"),
            "owner_proposed": metric.get("owner_proposed"),
            "definition_file": metric["_file"],
            "caveats": metric.get("caveats", []),
            "lineage_notes": " ".join((metric.get("lineage_notes") or "").split()),
        }
        if metric["status"] == "blocked":
            entry["blocked_reason"] = " ".join(metric["blocked_reason"].split())
            entry["unblock_requires"] = metric.get("unblock_requires", [])
            entry["queryable"] = False
        else:
            entry["queryable"] = True
            entry["sql_model"] = f"mtr_{metric['name']}"
            entry["numerator"] = metric["numerator"]
            entry["denominator"] = metric["denominator"]
            entry["filters"] = metric.get("filters") or []
            entry["filters_described"] = [
                describe_filter(f) for f in (metric.get("filters") or [])]
            entry["time_comparisons"] = metric.get("time_comparisons") or []
            entry["is_reaggregatable"] = is_reaggregatable(metric)
            if metric.get("provisional_reason"):
                entry["provisional_reason"] = " ".join(metric["provisional_reason"].split())
            if metric.get("companion_metric"):
                entry["companion_metric"] = metric["companion_metric"]
        payload["metrics"].append(entry)

    # The process map is loaded from the seed so the JSON contract answers
    # "which dashboard is this on" without a second lookup.
    map_path = os.path.join(ROOT, "seeds", "process_metric_map.csv")
    process_map = {}
    if os.path.exists(map_path):
        import csv
        with open(map_path) as fh:
            for row in csv.DictReader(fh):
                process_map.setdefault(row["metric_name"], []).append(
                    {"process_code": row["process_code"], "slot": row["slot"]})
    for entry in payload["metrics"]:
        entry["processes"] = process_map.get(entry["name"], [])

    return [write("exports/semantic/metric_registry.json",
                  json.dumps(payload, indent=2) + "\n")]


