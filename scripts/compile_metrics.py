GENERATED_BANNER = (
    "Generated by scripts/compile_metrics.py from semantic/metrics/. "
    "Do not edit by hand - edit the metric definition and recompile."
)

AGGS = {
    "sum": "sum({expr})",
    "count": "count({expr})",
    "count_distinct": "count(distinct {expr})",
    "avg": "avg({expr})",
    "min": "min({expr})",
    "max": "max({expr})",
}

# Aggregations whose pre-aggregated result can be summed back up to a coarser
# grain. count_distinct cannot: summing distinct counts double-counts anything
# that spans two dimension values.
REAGGREGATABLE = {"sum", "count"}

DAX_AGG = {
    "sum": "SUM({table}[{col}])",
    "count": "COUNTA({table}[{col}])",
    "count_distinct": "DISTINCTCOUNT({table}[{col}])",
    "avg": "AVERAGE({table}[{col}])",
    "min": "MIN({table}[{col}])",
    "max": "MAX({table}[{col}])",
}

CUBE_AGG = {
    "sum": "sum",
    "count": "count",
    "count_distinct": "count_distinct",
    "avg": "avg",
    "min": "min",
    "max": "max",
}

DBT_SEMANTIC_AGG = {
    "sum": "sum",
    "count": "count",
    "count_distinct": "count_distinct",
    "avg": "average",
    "min": "min",
    "max": "max",
}

DAX_FORMAT = {
    "percent": '"0.0%"',
    "currency_usd": '"\\$#,0.00"',
    "days": '"#,0.0"',
    "count": '"#,0"',
}

# --------------------------------------------------------------------------
# Filters (D7)
#
# A filter is a structured triple - column, op, and a value for the comparison
# ops - never a SQL string. Every renderer maps the op to its own dialect from
# the table below, so there is no parsing anywhere and a translation bug is
# unrepresentable rather than merely guarded against.
#
# This replaced a `str.split`-based SQL translator that silently mangled `>=`
# into a column named `days_late >` - the exact class of bug this shape makes
# impossible. It also closes the tool-neutrality claim in open question 5: the
# supported grammar is now declared and finite instead of "whatever the parser
# happens to cope with".
#
# `column` is strictly a column on the base model. A metric needing a
# derivation puts it on the fact, which is already this project's rule.
# --------------------------------------------------------------------------

#: op -> (needs a value, SQL template, DAX template, arity note)
OPS = {
    "is_true":     (False, "{c}",                 "{t}[{c}] = TRUE()"),
    "is_false":    (False, "not {c}",             "{t}[{c}] = FALSE()"),
    "is_null":     (False, "{c} is null",         "ISBLANK({t}[{c}])"),
    "is_not_null": (False, "{c} is not null",     "NOT ISBLANK({t}[{c}])"),
    "eq":          (True,  "{c} = {v}",           "{t}[{c}] = {v}"),
    "ne":          (True,  "{c} <> {v}",          "{t}[{c}] <> {v}"),
    "gt":          (True,  "{c} > {v}",           "{t}[{c}] > {v}"),
    "gte":         (True,  "{c} >= {v}",          "{t}[{c}] >= {v}"),
    "lt":          (True,  "{c} < {v}",           "{t}[{c}] < {v}"),
    "lte":         (True,  "{c} <= {v}",          "{t}[{c}] <= {v}"),
    "in":          (True,  None,                  None),   # rendered specially
}


# --------------------------------------------------------------------------
# P9 - time intelligence
#
# Year-on-year, month-to-date and rolling-12 genuinely belong in DAX: they are
# functions of filter context rather than properties of the metric, and pushing
# them into dbt means materialising a comparison per grain. But they are also
# the first thing a report author hand-writes, and the moment someone types
# "Cost Per Shipment YoY" they pick a date column - which is a measure decision
# made in Power BI.
#
# Emitting them from the registry keeps that on the right side of the rule in
# architecture.md: no measure logic authored in Power BI. The date column comes
# from the metric's own binding in semantic/models.yml, never a guess.
# --------------------------------------------------------------------------

#: name -> (suffix, DAX wrapper around the base measure)
TIME_COMPARISONS = {
    "yoy": ("YoY", "CALCULATE({m}, SAMEPERIODLASTYEAR({d}))"),
    "yoy_pct": ("YoY %", "DIVIDE({m} - CALCULATE({m}, SAMEPERIODLASTYEAR({d})), "
                         "CALCULATE({m}, SAMEPERIODLASTYEAR({d})))"),
    "mtd": ("MTD", "TOTALMTD({m}, {d})"),
    "ytd": ("YTD", "TOTALYTD({m}, {d})"),
    "rolling_12": ("Rolling 12", "CALCULATE({m}, DATESINPERIOD({d}, MAX({d}), -12, MONTH))"),
}


def sql_literal(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def dax_literal(value):
    if isinstance(value, bool):
        return "TRUE()" if value else "FALSE()"
    if isinstance(value, (int, float)):
        return str(value)
    return '"' + str(value).replace('"', '""') + '"'


def filter_sql(spec):
    column, op = spec["column"], spec["op"]
    if op == "in":
        values = ", ".join(sql_literal(v) for v in spec["value"])
        return f"{column} in ({values})"
    return OPS[op][1].format(c=column, v=sql_literal(spec.get("value")))


def filter_dax(table, spec):
    column, op = spec["column"], spec["op"]
    if op == "in":
        clauses = " || ".join(
            f"{table}[{column}] = {dax_literal(v)}" for v in spec["value"])
        return f"FILTER(ALL({table}[{column}]), {clauses})"
    return OPS[op][2].format(t=table, c=column, v=dax_literal(spec.get("value")))


def filters_sql(specs):
    return [filter_sql(f) for f in (specs or [])]


def describe_filter(spec):
    """Human-readable form, for docs and catalogue output."""
    if spec["op"] == "in":
        return f"{spec['column']} in ({', '.join(str(v) for v in spec['value'])})"
    if OPS[spec["op"]][0]:
        return f"{spec['column']} {spec['op']} {spec['value']}"
    return f"{spec['column']} {spec['op'].replace('_', ' ')}"


