_project_vars: dict = {}


def project_var(name, default=None):
    """Read a var out of dbt_project.yml.

    Every other consumer of these values reads them through dbt. Anything the
    compiler emits should agree with what dbt computes, so it reads the same
    source rather than restating the value.
    """
    if not _project_vars:
        with open(os.path.join(ROOT, "dbt_project.yml")) as fh:
            _project_vars.update(yaml.safe_load(fh).get("vars") or {})
    return _project_vars.get(name, default)


def load_registry():
    dimensions = yaml.safe_load(open(os.path.join(SEMANTIC, "dimensions.yml")))["dimensions"]
    models = yaml.safe_load(open(os.path.join(SEMANTIC, "models.yml")))["models"]
    metrics = []
    metric_dir = os.path.join(SEMANTIC, "metrics")
    for filename in sorted(os.listdir(metric_dir)):
        if not filename.endswith((".yml", ".yaml")):
            continue
        metric = yaml.safe_load(open(os.path.join(metric_dir, filename)))
        metric["_file"] = os.path.join("semantic", "metrics", filename)
        metrics.append(metric)
    return dimensions, models, metrics


# --------------------------------------------------------------------------
# Field consumption
#
# Two renderers walk the same YAML - SQL here, DAX via export_powerbi.py - and
# each is free to interpret or ignore any field. Nothing noticed when `filters`
# reached only the SQL target, and the warehouse and the dashboard disagreed
# about Cost Per Order by 17.3%. This table makes silently ignoring a field a
# build failure.
#
# Adding a semantic field means adding it here and to every target that must
# honour it. That is the point: the compiler refuses to ship a definition it
# cannot fully express.
# --------------------------------------------------------------------------

#: Fields that change what a metric computes. Presentation-only fields
#: (label, format, direction, owner, notes) are deliberately absent.
SEMANTIC_FIELDS = {"base_model", "numerator", "denominator", "filters", "dimensions"}

#: Which of those each computational target actually honours.
#:
#: `dimensions` is honoured differently by target and that difference is real,
#: not a loophole. sql names the dimensions in its GROUP BY. dax honours them
#: *structurally*: scripts/export_powerbi.py builds a relationship per
#: dimension binding, and a DAX measure is slice-agnostic by construction, so
#: the measure text never mentions them.
CONSUMES = {
    "sql": {"base_model", "numerator", "denominator", "filters", "dimensions"},
    "dax": {"base_model", "numerator", "denominator", "filters", "dimensions"},
}

REQUIRED_FIELDS = [
    "name", "label", "status", "description", "grain",
    "base_model", "numerator", "denominator", "filters", "dimensions",
    "owner", "blocked_reason",
]

VALID_STATUS = {"active", "provisional", "blocked"}


def validate(dimensions, models, metrics, verbose=True):
    """Governance lives here. A metric that cannot be validated cannot ship.

    One check degrades rather than failing: column existence needs
    target/catalog.json, which only exists after a `dbt docs generate`. On a
    clean checkout the compiler still runs, but it says so - a silent skip
    would mean "Registry OK" without the strongest check having run.
    """
    errors = []
    seen = {}
    skipped_column_check = False

    for metric in metrics:
        name = metric.get("name", "<unnamed>")
        where = metric["_file"]

        for field in REQUIRED_FIELDS:
            if field not in metric:
                errors.append(f"{where}: missing required field '{field}'")

        if name in seen:
            errors.append(f"{where}: metric '{name}' is already defined in {seen[name]}")
        seen[name] = where

        if metric.get("name") != os.path.splitext(os.path.basename(where))[0]:
            errors.append(f"{where}: filename must match the metric name '{name}'")

        status = metric.get("status")
        if status not in VALID_STATUS:
            errors.append(f"{where}: status '{status}' must be one of {sorted(VALID_STATUS)}")

        if "owner" not in metric:
            errors.append(f"{where}: every metric needs an owner field, even if it is TBD")

        # Every dimension a metric asks for must be conformed, and the base
        # model must know how to reach it. This is the check that stops
        # "customer" quietly meaning three different things.
        for dim in metric.get("dimensions") or []:
            if dim not in dimensions:
                errors.append(f"{where}: dimension '{dim}' is not in semantic/dimensions.yml")

        if status == "blocked":
            if not metric.get("blocked_reason"):
                errors.append(f"{where}: blocked metrics must state blocked_reason")
            if metric.get("base_model") or metric.get("numerator"):
                errors.append(f"{where}: blocked metrics must not carry SQL")
            continue

        base = metric.get("base_model")
        if base not in models:
            errors.append(f"{where}: base_model '{base}' is not in semantic/models.yml")
            continue

        bound = models[base].get("dimensions") or {}
        for dim in metric.get("dimensions") or []:
            if dim not in bound:
                errors.append(
                    f"{where}: base_model '{base}' has no binding for dimension '{dim}' "
                    f"- add it to semantic/models.yml"
                )

        columns = base_model_columns(base)
        referenced = []

        for side in ("numerator", "denominator"):
            spec = metric.get(side)
            if not isinstance(spec, dict):
                errors.append(f"{where}: {side} must be a mapping with agg and column")
                continue
            if spec.get("agg") not in AGGS:
                errors.append(f"{where}: {side}.agg '{spec.get('agg')}' unknown; "
                              f"expected one of {sorted(AGGS)}")
            if spec.get("expression"):
                errors.append(
                    f"{where}: {side}.expression is no longer supported. Rename it to "
                    f"'column' - it must be a bare column on {base}, and any derivation "
                    f"belongs on the fact model."
                )
            if not spec.get("column"):
                errors.append(f"{where}: {side}.column is required")
            else:
                referenced.append((f"{side}.column", spec["column"]))
            errors += filter_errors(spec.get("filter"), f"{where}: {side}.filter",
                                    referenced, f"{side}.filter")

        for index, spec in enumerate(metric.get("filters") or []):
            errors += filter_errors(spec, f"{where}: filters[{index}]",
                                    referenced, f"filters[{index}]")

        # Every column named must exist on the base model. Cheap now that
        # columns are bare references rather than arbitrary SQL. Skipped with a
        # note when the warehouse has not been built, so the compiler still
        # runs on a clean checkout.
        if columns is None:
            skipped_column_check = True
        else:
            for label, column in referenced:
                if column not in columns:
                    errors.append(
                        f"{where}: {label} names '{column}', which is not a column on "
                        f"{base}. Available: {', '.join(sorted(columns)[:8])}..."
                    )

        # A field that some computational target ignores is a definition
        # that compiles to something it does not describe.
        set_fields = {f for f in SEMANTIC_FIELDS if metric.get(f)}
        for target, consumed in sorted(CONSUMES.items()):
            dropped = set_fields - consumed
            if dropped:
                errors.append(
                    f"{where}: target '{target}' does not consume {sorted(dropped)} - "
                    f"the compiled artefact would compute something the definition does "
                    f"not describe. Either honour the field in that target or remove it "
                    f"from SEMANTIC_FIELDS."
                )

        if status == "provisional" and not metric.get("provisional_reason"):
            errors.append(f"{where}: provisional metrics must state provisional_reason")

    if skipped_column_check and verbose:
        print(
            "  note: column existence NOT checked - target/catalog.json is "
            "absent.\n"
            "        Run `dbt docs generate` and recompile to enable it. Until "
            "then a\n"
            "        typo in a numerator, denominator or filter column compiles "
            "cleanly\n"
            "        into every artefact and fails later, somewhere nobody "
            "is watching.",
            file=sys.stderr,
        )

    if errors:
        raise RegistryError("\n".join("  - " + e for e in errors))


def filter_errors(spec, where, referenced, label):
    """Validate one structured filter. Returns a list of errors."""
    if spec is None:
        return []
    if not isinstance(spec, dict):
        return [f"{where}: a filter must be a mapping with column and op, not a "
                f"SQL string. Supported ops: {', '.join(sorted(OPS))}"]
    errors = []
    if not spec.get("column"):
        errors.append(f"{where}: column is required")
    else:
        referenced.append((label, spec["column"]))
    op = spec.get("op")
    if op not in OPS:
        errors.append(f"{where}: op '{op}' unknown; expected one of {sorted(OPS)}")
        return errors
    needs_value = OPS[op][0]
    has_value = "value" in spec
    if needs_value and not has_value:
        errors.append(f"{where}: op '{op}' requires a value")
    if not needs_value and has_value:
        errors.append(f"{where}: op '{op}' takes no value")
    if op == "in" and has_value and not isinstance(spec["value"], list):
        errors.append(f"{where}: op 'in' requires a list of values")
    return errors


_column_cache: dict = {}


def base_model_columns(model_name):
    """Columns of a mart model, from the dbt catalogue when one exists.

    Returns None when the warehouse has not been built, so validation degrades
    to "cannot check" rather than failing on a clean checkout.
    """
    if not _column_cache:
        catalog = os.path.join(ROOT, "target", "catalog.json")
        if not os.path.exists(catalog):
            _column_cache["_absent"] = True
        else:
            with open(catalog) as fh:
                nodes = json.load(fh).get("nodes", {})
            for node in nodes.values():
                name = node.get("metadata", {}).get("name")
                if name:
                    _column_cache[name] = set(node.get("columns", {}))
    if _column_cache.get("_absent"):
        return None
    return _column_cache.get(model_name)


def agg_sql(spec):
    rendered = AGGS[spec["agg"]].format(expr=spec["column"])
    if spec.get("filter"):
        rendered += f" filter (where {filter_sql(spec['filter'])})"
    return rendered


def is_reaggregatable(metric):
    if metric.get("status") == "blocked":
        return None
    return (metric["numerator"]["agg"] in REAGGREGATABLE
            and metric["denominator"]["agg"] in REAGGREGATABLE)


def active_metrics(metrics):
    return [m for m in metrics if m.get("status") in ("active", "provisional")]


def write(path, content):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w") as fh:
        fh.write(content)
    return path


